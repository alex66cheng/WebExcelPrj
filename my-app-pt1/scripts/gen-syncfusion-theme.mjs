// Generates src/styles/syncfusion-greenwave.css: re-colours the Syncfusion Material
// theme (pink accent #e3165b, indigo primary #3f51b5) to the Greenwave teal used by
// the rest of the app (see src/index.css). Only the declarations that use those two
// colours are copied, under their original selectors; likeexcel.tsx imports the file
// right after the Material stylesheets, so these same-specificity rules win by order.
//
// Run from my-app-pt1/ after upgrading @syncfusion packages:
//   node scripts/gen-syncfusion-theme.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);

// Keep in sync with the Material imports at the top of src/pages/likeexcel.tsx.
const PACKAGES = [
  'ej2-base', 'ej2-inputs', 'ej2-buttons', 'ej2-splitbuttons', 'ej2-lists',
  'ej2-navigations', 'ej2-popups', 'ej2-dropdowns', 'ej2-grids', 'ej2-spreadsheet',
];

const TEAL = '#1E6F64';
const TEAL_RGB = '30, 111, 100';
const ACCENT = /#e3165b|#3f51b5|rgba\(\s*(227,\s*22,\s*91|63,\s*81,\s*181)\s*,/i;
const recolor = (decl) => decl
  .replace(/#e3165b|#3f51b5/gi, TEAL)
  .replace(/rgba\(\s*(?:227,\s*22,\s*91|63,\s*81,\s*181)\s*,/gi, `rgba(${TEAL_RGB},`);

const out = [];
for (const pkg of PACKAGES) {
  const file = require.resolve(`@syncfusion/${pkg}/styles/material.css`);
  const css = fs.readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  let count = 0;
  // Flat rules only (skip @-rule wrappers such as @font-face / @keyframes / @media).
  for (const [, selector, body] of css.matchAll(/([^{}@]+)\{([^{}]*)\}/g)) {
    const decls = body.split(';').map((d) => d.trim()).filter((d) => ACCENT.test(d));
    if (!decls.length) continue;
    out.push(`${selector.trim()} {\n  ${decls.map(recolor).join(';\n  ')};\n}`);
    count++;
  }
  console.log(`${pkg}: ${count} rules`);
}

const target = path.resolve('src/styles/syncfusion-greenwave.css');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(
  target,
  `/* Generated by scripts/gen-syncfusion-theme.mjs — do not edit by hand. */\n\n${out.join('\n\n')}\n`,
);
console.log(`wrote ${target} (${out.length} rules)`);
